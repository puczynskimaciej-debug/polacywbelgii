const originalContent = new Map();

function applyLanguage(language) {
  const selected = languageData[language] ? language : "pl";
  const dictionary = translations[selected];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    if (!originalContent.has(element)) originalContent.set(element, element.textContent);
    element.textContent = dictionary[element.dataset.i18n] ?? originalContent.get(element);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    if (!originalContent.has(element)) originalContent.set(element, element.innerHTML);
    element.innerHTML = dictionary[element.dataset.i18nHtml] ?? originalContent.get(element);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(element => {
    element.setAttribute('aria-label', dictionary[element.dataset.i18nAria] || element.getAttribute('aria-label'));
  });
  const articleBody = document.querySelector(".prose[data-i18n-html]");
  const translatedBody = document.querySelector(`template[data-article-translation="${selected}"]`);
  if (articleBody && translatedBody) articleBody.innerHTML = translatedBody.innerHTML;
  document.querySelectorAll("[data-translation-en], [data-translation-nl], [data-translation-fr]").forEach((element) => {
    if (!originalContent.has(element)) originalContent.set(element, element.textContent);
    const translated = element.getAttribute(`data-translation-${selected}`);
    element.textContent = selected === "pl" || !translated ? originalContent.get(element) : translated;
  });
  document.querySelectorAll("[data-category]").forEach((element) => {
    if (!originalContent.has(element)) originalContent.set(element, element.textContent);
    const original = originalContent.get(element);
    element.textContent = dictionary[`category.${original}`] ?? original;
  });
  document.querySelectorAll('[data-article-image-link]').forEach(element => {
    const title = element.closest('article')?.querySelector('h2 a')?.textContent;
    if (title) element.setAttribute('aria-label', `${selected === 'en' ? 'Read' : selected === 'fr' ? 'Lire' : selected === 'nl' ? 'Lees' : 'Czytaj'}: ${title}`);
  });
  document.querySelectorAll("time[datetime]").forEach((element) => {
    const date = new Date(element.getAttribute("datetime"));
    if (!Number.isNaN(date.valueOf())) {
      element.textContent = new Intl.DateTimeFormat(languageData[selected].locale, {
        day: "numeric", month: "long", year: "numeric"
      }).format(date);
    }
  });

  document.documentElement.lang = selected;
  const articleHeading = document.querySelector(".single-article__header h1");
  const pageTitle = articleHeading?.textContent || (document.body.dataset.page === 'order' ? dictionary['ads.order'] : pageTitles[selected]?.[document.body.dataset.page]);
  if (selected === "pl") document.title = originalDocumentTitle;
  else if (pageTitle) document.title = `${pageTitle} | Polacy w Belgii`;
  const description = document.querySelector('meta[name="description"]');
  if (description && pageDescriptions[selected]?.[document.body.dataset.page]) description.content = pageDescriptions[selected][document.body.dataset.page];
  else if (description && originalMetaDescription) description.content = originalMetaDescription;
  document.querySelector(".language-picker__button img").src = languageData[selected].flag;
  document.querySelector(".language-picker__code").textContent = languageData[selected].code;
  document.querySelectorAll("[data-lang]").forEach((button) =>
    button.classList.toggle("is-active", button.dataset.lang === selected)
  );
  localStorage.setItem("siteLanguage", selected);
  applyCmsContent(selected);
  document.dispatchEvent(new CustomEvent("languagechange", { detail: selected }));
}

function applyCmsContent(language) {
  const data=window.cmsLocalized;if(!data)return;
  const home=language==='pl'?data.home:data.home.locales?.[language];
  const site=language==='pl'?data.site:data.site.locales?.[language];
  const set=(key,value)=>{document.querySelectorAll(`[data-i18n="${key}"]`).forEach(e=>e.textContent=value||'');};
  if(home && document.body.dataset.page==='home'){
    for(const key of ['eyebrow','title','description'])set('home.'+key,home.hero[key]);
    for(const [group,selector] of [['news','.news-grid'],['notices','.notice-grid']]){
      const container=document.querySelector(selector);if(!container)continue;
      container.replaceChildren(...home[group].map((item,index)=>{
        const card=document.createElement('article');card.className=group==='news'?'news-card':'notice';
        if(group==='news')card.dataset.region=data.home.news[index]?.region||'all';
        const add=(tag,value,className)=>{const e=document.createElement(tag);e.textContent=value||'';if(className)e.className=className;return e;};
        if(group==='news'){const image=document.createElement('img');image.src=item.image;image.alt='';image.loading='lazy';const body=document.createElement('div');body.className='news-card__body';const link=add('a',translations[language]['common.more']||'Dowiedz się więcej','card-link');link.href=item.link;body.append(add('span',item.category,'tag'),add('h3',item.title),add('p',item.description),link);card.append(image,body);}
        else {const top=document.createElement('div');top.className='notice__top';top.append(add('span',item.category,'tag'),add('time',item.date));card.append(top,add('h3',item.title),add('p',item.description),add('p',item.contact,'notice__contact'));}return card;
      }));
    }
  }
  if(site){set('contact.heading',site.contact.heading);set('contact.text',site.contact.description);set('contact.belgium',site.contact.area);const email=document.querySelector('.contact-detail a');if(email){email.textContent=site.contact.email;email.href='mailto:'+site.contact.email;}
    const seo=site.seo?.[document.body.dataset.page];if(seo){document.title=seo.title;document.querySelector('meta[name=description]')?.setAttribute('content',seo.description);}
  }
}

const toggle = document.querySelector(".nav-toggle");
const navigation = document.querySelector(".main-nav");
const languagePicker = document.querySelector(".language-picker");
const languageButton = document.querySelector(".language-picker__button");

if (toggle && navigation) {
  toggle.addEventListener("click", () => {
    const isOpen = toggle.getAttribute("aria-expanded") === "true";
    toggle.setAttribute("aria-expanded", String(!isOpen));
    navigation.classList.toggle("is-open", !isOpen);
    document.body.classList.toggle("menu-open", !isOpen);
  });
}

if (languagePicker && languageButton) {
  languageButton.addEventListener("click", () => {
    const isOpen = languageButton.getAttribute("aria-expanded") === "true";
    languageButton.setAttribute("aria-expanded", String(!isOpen));
    languagePicker.classList.toggle("is-open", !isOpen);
  });
  languagePicker.addEventListener("click", (event) => {
    const option = event.target.closest("[data-lang]");
    if (!option) return;
    applyLanguage(option.dataset.lang);
    languageButton.setAttribute("aria-expanded", "false");
    languagePicker.classList.remove("is-open");
  });
  document.addEventListener("click", (event) => {
    if (!languagePicker.contains(event.target)) {
      languageButton.setAttribute("aria-expanded", "false");
      languagePicker.classList.remove("is-open");
    }
  });
}

