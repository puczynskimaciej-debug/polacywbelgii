import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { randomBytes,randomUUID } from 'node:crypto';
import { chromium } from 'playwright-core';
import { hashPassword } from '../cloudflare/auth.mjs';
import { openLocalDb } from '../agent/local-db.mjs';

const db=openLocalDb();
const adminId=randomUUID(),email=`cms-actions-${adminId}@example.invalid`,password=randomBytes(30).toString('base64url'),candidateId=randomBytes(10).toString('hex');
const title='Test redakcyjny interfejsu CMS — akceptacja i harmonogram';
const now=new Date().toISOString();
db.prepare('INSERT INTO cms_users(id,email,name,password_hash,role,active,must_change_password) VALUES(?,?,?,?,?,1,0)').run(adminId,email,'Test akcji CMS',await hashPassword(password),'admin');
db.prepare('INSERT INTO ai_candidates(id,kind,status,title,description,body,category,region,sources_json,verification_json,created_at,updated_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?)').run(candidateId,'article','pending_review',title,'Test lokalny bez publikacji','## Treść testowa\n\nTo jest lokalny materiał testowy służący wyłącznie do sprawdzenia interfejsu CMS. '.repeat(3),'Praca','all','[{"url":"https://www.gov.pl/web/belgia/praca-i-pobyt"}]','{"status":"needs_review"}',now,now);
db.prepare('INSERT INTO ai_editorial(candidate_id,status,owner_kind,owner_id,updated_at) VALUES(?,?,?,?,?)').run(candidateId,'pending_review','agent','agent',now);
const browser=await chromium.launch({executablePath:process.env.BROWSER_PATH||'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',headless:true});
try{
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://localhost:8080/admin/');
  await page.locator('#login-form input[name=email]').fill(email);
  await page.locator('#login-form input[name=password]').fill(password);
  await page.locator('#login-form button').click();
  await page.locator('#app-view').waitFor({state:'visible',timeout:15000});
  await page.locator('.nav-item[data-view=ai-editor]').click();
  await page.locator('#ai-search').fill(title);
  await page.locator('#ai-queue [data-ai-open]').first().click();
  await page.locator('#ai-detail-actions [data-ai-action=approved]').click();
  await page.waitForFunction(()=>document.querySelector('#ai-detail-meta')?.textContent.includes('Zaakceptowany'));
  assert.equal(db.prepare('SELECT status FROM ai_editorial WHERE candidate_id=?').get(candidateId).status,'approved');
  await page.locator('#ai-detail-actions [data-ai-action=schedule]').click();
  await page.locator('#ai-schedule-form input[name=date]').fill('2027-03-28');
  await page.locator('#ai-schedule-form input[name=time]').fill('02:30');
  assert.match(await page.locator('#ai-schedule-availability').innerText(),/nie istnieje/);
  await page.locator('#ai-schedule-form input[name=date]').fill('2027-10-31');
  assert.equal(await page.locator('#ai-fold-label').isVisible(),true);
  const future=new Date(Date.now()+7*86400000).toLocaleDateString('sv-SE',{timeZone:'Europe/Brussels'});
  await page.locator('#ai-schedule-form input[name=date]').fill(future);
  await page.locator('#ai-schedule-form input[name=time]').fill('11:00');
  await page.screenshot({path:path.join(path.resolve(import.meta.dirname,'..'),'.local','cms-redesign-schedule.png')});
  await page.locator('#ai-schedule-form button[type=submit]').click();
  await page.locator('#ai-schedule-dialog').waitFor({state:'hidden',timeout:15000});
  const record=db.prepare('SELECT status,scheduled_at,approved_by,public_state FROM ai_editorial WHERE candidate_id=?').get(candidateId);
  assert.equal(record.status,'scheduled');assert.equal(record.approved_by,adminId);assert.equal(record.public_state,'hidden');
  assert.equal(fs.existsSync(path.join(path.resolve(import.meta.dirname,'..'),'src','content','articles',`ai-${candidateId}.md`)),false);
  await page.locator('#ai-detail-dialog [data-close]').click();
  await page.locator('.nav-item[data-view=ai-calendar]').click();
  await page.locator('#ai-calendar-start').fill(future);
  await page.locator('#ai-calendar-view').selectOption('list');
  await page.locator('#ai-calendar-list [data-ai-open]').filter({hasText:title}).waitFor();
  await page.locator('.nav-item[data-view=ai-editor]').click();
  await page.locator('#ai-search').fill(title);
  await page.locator('#ai-queue [data-ai-open]').first().click();
  if(!await page.locator('#ai-detail-actions .action-menu').evaluate(node=>node.open))await page.locator('#ai-detail-actions .action-menu summary').click();
  await page.locator('#ai-detail-actions [data-ai-action=rejected]').click();
  await page.keyboard.press('Escape');
  assert.equal(db.prepare('SELECT status FROM ai_editorial WHERE candidate_id=?').get(candidateId).status,'scheduled');
  if(!await page.locator('#ai-detail-actions .action-menu').evaluate(node=>node.open))await page.locator('#ai-detail-actions .action-menu summary').click();
  await page.locator('#ai-detail-actions [data-ai-action=rejected]').click();
  await page.locator('#cms-confirm-accept').click();
  await page.waitForFunction(()=>document.querySelector('#ai-detail-meta')?.textContent.includes('Odrzucony'));
  assert.equal(db.prepare('SELECT status FROM ai_editorial WHERE candidate_id=?').get(candidateId).status,'rejected');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({approved:true,scheduled:true,dstGapRejected:true,dstFoldShown:true,calendarVisible:true,rejectionConfirmed:true,publicState:record.public_state,errors}));
}finally{
  await browser.close();
  db.prepare('DELETE FROM ai_candidate_history WHERE candidate_id=?').run(candidateId);
  db.prepare('DELETE FROM ai_editorial WHERE candidate_id=?').run(candidateId);
  db.prepare('DELETE FROM ai_candidates WHERE id=?').run(candidateId);
  db.prepare('DELETE FROM cms_sessions WHERE user_id=?').run(adminId);
  db.prepare('DELETE FROM cms_audit WHERE actor_id=?').run(adminId);
  db.prepare('DELETE FROM cms_users WHERE id=?').run(adminId);
  db.close();
}
