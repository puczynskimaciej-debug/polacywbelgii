import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { DatabaseSync } from 'node:sqlite';
import { chromium } from 'playwright-core';
import { localD1Path } from '../agent/local-db.mjs';

const origin = 'http://localhost:8080';
const db = new DatabaseSync(localD1Path());
db.exec('PRAGMA busy_timeout=5000');
const browser = await chromium.launch({executablePath:process.env.BROWSER_PATH || 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',headless:true});
const localDay = value => new Intl.DateTimeFormat('sv-SE',{timeZone:'Europe/Brussels',year:'numeric',month:'2-digit',day:'2-digit'}).format(value);
const shift = (days,hour=12) => { const date = new Date(); date.setUTCDate(date.getUTCDate()+days); date.setUTCHours(hour,0,0,0); return date; };
const start = shift(3), end = shift(5), eventDate = localDay(start);
const sourceUrl = 'https://instytutpolski.pl/brussels/en/';
const event = {title:'Test wydarzenia wielodniowego',description:'Tylko test przeglądarkowy.',start:start.toISOString(),end:end.toISOString(),city:'Bruksela',venue:'Sala testowa',organizer:'Instytut Polski',sourceUrl};
const id = randomUUID(), adTitle = `Test płatnej emisji ${id.slice(0,8)}`;
const order = {id,kind:'text',type:'STANDARD',language:'pl',company:'Firma testowa',title:adTitle,description:'Testowa treść zamówienia z lokalnej D1.',contact:'kontakt@example.invalid',startDate:localDay(shift(-1)),endDate:localDay(shift(10)),status:'approved',paymentStatus:'paid',source:'public',createdAt:new Date().toISOString()};
const save = value => db.prepare('INSERT INTO ad_orders(id,data,created_at) VALUES(?,?,?) ON CONFLICT(id) DO UPDATE SET data=excluded.data').run(id,JSON.stringify(value),order.createdAt);
const noOverflow = page => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1);
try {
  const calendar = await browser.newPage({viewport:{width:390,height:844}});
  await calendar.route('**/api/public-events',route => route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({events:[event]})}));
  await calendar.goto(origin);
  await calendar.locator('[data-event-open]').click();
  const dialog = calendar.locator('#event-calendar-dialog');
  await dialog.waitFor({state:'visible'});
  assert.equal(await calendar.locator('body').evaluate(node => getComputedStyle(node).overflow),'hidden');
  assert.equal(await calendar.locator('.event-weekday').allTextContents().then(days => days[0]),'Pon');
  for(let offset=3;offset<=5;offset++){
    const date=localDay(shift(offset));
    if(date.slice(0,7)===eventDate.slice(0,7)) assert.equal(await calendar.locator(`[data-date="${date}"]`).evaluate(node => node.classList.contains('has-events')),true);
  }
  await calendar.locator(`[data-date="${eventDate}"]`).click();
  await calendar.locator('.event-day-event').click();
  assert.equal(await calendar.getByRole('link',{name:'Strona organizatora →'}).getAttribute('href'),sourceUrl);
  assert.equal(await noOverflow(calendar),true);
  await calendar.setViewportSize({width:360,height:740});
  assert.equal(await noOverflow(calendar),true);
  await calendar.setViewportSize({width:768,height:1024});
  assert.equal(await noOverflow(calendar),true);
  await calendar.setViewportSize({width:1440,height:900});
  assert.equal(await noOverflow(calendar),true);
  assert.ok(await dialog.evaluate(node => node.getBoundingClientRect().width <= 901));
  await calendar.keyboard.press('Escape');
  assert.equal(await dialog.isVisible(),false);
  assert.equal(await calendar.locator('[data-event-open]').evaluate(node => node===document.activeElement),true);
  await calendar.goto(`${origin}/wydarzenia/`);
  await dialog.waitFor({state:'visible'});
  const monthBefore=await calendar.locator('#event-month-title').textContent();
  await calendar.locator('[data-event-month="next"]').click();
  assert.notEqual(await calendar.locator('#event-month-title').textContent(),monthBefore);
  await calendar.locator('[data-event-close]').click();
  await calendar.close();

  const ads = await browser.newPage({viewport:{width:1280,height:900}});
  const image='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=';
  const fixture=[{...order,id:randomUUID(),type:'PREMIUM',kind:'image',image,imageMobile:image,url:sourceUrl},{...order,id:randomUUID(),type:'TOP',kind:'image',image,url:sourceUrl},{...order,id:randomUUID(),type:'STANDARD'}];
  await ads.route('**/api/ads?action=public*',route => route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({ads:fixture})}));
  await ads.goto(`${origin}/ogloszenia/`);
  await ads.locator('#listing-premium .premium-banner__link').waitFor();
  assert.equal(await ads.locator('#listing-top .listing-card').count(),1);
  assert.equal(await ads.locator('.ads-standard-list .listing-card').count(),1);
  assert.equal(await ads.locator('.ads-standard-list').evaluate(node => getComputedStyle(node).gridAutoFlow),'row');
  assert.equal(await noOverflow(ads),true);
  await ads.setViewportSize({width:768,height:900});
  assert.equal(await noOverflow(ads),true);
  await ads.setViewportSize({width:390,height:844});
  assert.equal(await ads.locator('.listing-top-grid').evaluate(node => getComputedStyle(node).gridTemplateColumns.split(' ').length),1);
  assert.equal(await noOverflow(ads),true);
  const expiring = [{ ...fixture[2], actualStartAt: new Date(Date.now() - 1000).toISOString(), actualEndAt: new Date(Date.now() + 3000).toISOString() }];
  await ads.unroute('**/api/ads?action=public*');
  await ads.route('**/api/ads?action=public*',route => route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({ads:expiring})}));
  await ads.reload();
  await ads.locator('.ads-standard-list .listing-card').waitFor();
  await ads.locator('.ads-standard-list .listing-card').waitFor({ state: 'detached', timeout: 6000 });
  await ads.unroute('**/api/ads?action=public*');
  await ads.route('**/api/ads?action=public*',route => route.fulfill({status:200,contentType:'application/json',body:'{"ads":[]}'}));
  await ads.reload();
  await ads.locator('#listing-premium .premium-banner__caption').getByText('DEMO').first().waitFor();
  assert.equal(await ads.locator('#listing-premium .premium-banner__link').count(), 2);
  assert.equal(await ads.locator('#listing-top .listing-card').count(), 5);
  assert.equal(await ads.locator('.ads-standard-list .listing-card').count(), 10);
  assert.equal(await ads.locator('.ads-standard-list .listing-card:visible').count(), 8);
  await ads.locator('.ad-show-more').click();
  assert.equal(await ads.locator('.ads-standard-list .listing-card:visible').count(), 10);
  assert.equal(await ads.locator('#listing-premium .ad-rotation-controls button').count(),0);
  await ads.locator('#listing-premium .ad-dots button').last().click();
  assert.equal(await ads.locator('#listing-premium .premium-banner__link.is-current').count(), 1);
  const currentBanner = await ads.locator('#listing-premium .premium-banner__link.is-current').evaluate(node => [...node.parentElement.children].indexOf(node));
  await ads.evaluate(() => document.activeElement.blur());
  await ads.waitForTimeout(5200);
  assert.equal(await ads.locator('#listing-premium .premium-banner__link.is-current').count(), 1);
  assert.notEqual(await ads.locator('#listing-premium .premium-banner__link.is-current').evaluate(node => [...node.parentElement.children].indexOf(node)), currentBanner);
  assert.ok(await ads.locator('#listing-top .demo-ad-label').count()>0);
  assert.ok(await ads.locator('.ads-standard-list .demo-ad-label').count()>0);
  assert.equal(await ads.locator('#ads-page-empty').isVisible(),false);
  await ads.goto(origin);
  await ads.locator('#listing-top .listing-card').first().waitFor();
  assert.equal(await ads.locator('#listing-top .listing-card').count(), 5);
  assert.equal(await ads.locator('#listing-top .ad-top-controls button').count(), 0);
  await ads.locator('#listing-top .ad-dots button').last().click();
  await ads.waitForTimeout(500);
  assert.ok(await ads.locator('#listing-top .top-carousel').evaluate(node => node.scrollLeft) > 0);
  assert.equal(await noOverflow(ads),true);
  await ads.locator('[data-order-open]:visible').first().click();
  await ads.locator('#order-dialog').waitFor({state:'visible'});
  await ads.locator('#order-close').click();
  await ads.unroute('**/api/ads?action=public*');

  save(order);
  await ads.goto(`${origin}/ogloszenia/`);
  await ads.getByText(adTitle,{exact:true}).waitFor();
  await ads.goto(origin);
  await ads.getByText(adTitle,{exact:true}).waitFor();
  save({...order,title:`${adTitle} po edycji`});
  await ads.reload(); await ads.getByText(`${adTitle} po edycji`,{exact:true}).waitFor();
  await ads.goto(`${origin}/ogloszenia/`); await ads.getByText(`${adTitle} po edycji`,{exact:true}).waitFor();
  save({...order,paymentStatus:'unpaid'});
  await ads.reload(); assert.equal(await ads.getByText(adTitle,{exact:false}).count(),0);
  await ads.goto(origin); assert.equal(await ads.getByText(adTitle,{exact:false}).count(),0);
  save({...order,status:'pending'});
  await ads.goto(`${origin}/ogloszenia/`); assert.equal(await ads.getByText(adTitle,{exact:false}).count(),0);
  await ads.goto(origin); assert.equal(await ads.getByText(adTitle,{exact:false}).count(),0);
  save({...order,status:'cancelled'});
  await ads.goto(`${origin}/ogloszenia/`); assert.equal(await ads.getByText(adTitle,{exact:false}).count(),0);
  await ads.goto(origin); assert.equal(await ads.getByText(adTitle,{exact:false}).count(),0);
  save({...order,endDate:localDay(shift(-2))});
  await ads.goto(`${origin}/ogloszenia/`); assert.equal(await ads.getByText(adTitle,{exact:false}).count(),0);
  await ads.goto(origin); assert.equal(await ads.getByText(adTitle,{exact:false}).count(),0);
  await ads.close();
  console.log('Calendar and ads browser E2E: modal, multi-day, keyboard, layouts, shared D1, edit, unpaid, expiry OK');
} finally {
  await browser.close();
  db.prepare('DELETE FROM ad_orders WHERE id=?').run(id);
  db.close();
}
