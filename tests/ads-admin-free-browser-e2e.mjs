import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { randomBytes, randomUUID } from 'node:crypto';
import { chromium } from 'playwright-core';
import { localD1Path } from '../agent/local-db.mjs';
import { hashPassword } from '../cloudflare/auth.mjs';
import domain from '../server/ads-domain.js';

const origin = process.env.LOCAL_CMS_ORIGIN || 'http://localhost:8080';
const db = new DatabaseSync(localD1Path());
db.exec('PRAGMA busy_timeout=5000');
const adminId = randomUUID(), password = randomBytes(32).toString('base64url');
const email = `admin-free-${adminId.slice(0, 12)}@example.invalid`;
const title = `Test bezpłatnego PREMIUM ${adminId.slice(0, 8)}`;
const today = domain.today();
const nextDay = new Date(Date.parse(today) + 86400000).toISOString().slice(0, 10);
const originalSettings = db.prepare('SELECT data,version FROM ads_settings WHERE id=1').get();
let browser, adId;
try {
  const settings = originalSettings ? JSON.parse(originalSettings.data) : domain.defaults();
  settings.markets.pl.enabled = true;
  Object.assign(settings.markets.pl.prices, { STANDARD: 200, TOP: 500, PREMIUM: 1000 });
  db.prepare('INSERT INTO ads_settings(id,data,version) VALUES(1,?,1) ON CONFLICT(id) DO UPDATE SET data=excluded.data').run(JSON.stringify(settings));
  db.prepare('INSERT INTO cms_users(id,email,name,password_hash,role,active,must_change_password) VALUES(?,?,?,?,?,1,0)').run(adminId, email, 'Admin Free E2E', await hashPassword(password), 'admin');
  browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH || 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true });
  const page = await browser.newPage();
  await page.goto(`${origin}/admin/`);
  await page.locator('#login-form [name="email"]').fill(email);
  await page.locator('#login-form [name="password"]').fill(password);
  await page.locator('#login-form [type="submit"]').click();
  await page.locator('#app-view').waitFor({ state: 'visible', timeout: 15000 });
  await page.locator('[data-view="ads"]').click();
  await page.locator('#ads-new').click();
  let form = page.frameLocator('#ads-order-frame');
  await form.locator('[name="adminComplimentary"]').waitFor({ state: 'visible' });
  await form.locator('[name="type"][value="PREMIUM"]').check();
  await form.locator(`#order-calendar button[data-date="${today}"]`).click();
  await form.locator('[data-title="pl"]').fill(title);
  await form.locator('[data-description="pl"]').fill('Testowa reklama administratora bez płatności Stripe.');
  const picture = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 1200; canvas.height = 720; const context = canvas.getContext('2d'); context.fillStyle = '#143b63'; context.fillRect(0, 0, 1200, 720); return canvas.toDataURL('image/png').split(',')[1]; });
  await form.locator('[name="imageFile"]').setInputFiles({ name: 'premium.png', mimeType: 'image/png', buffer: Buffer.from(picture, 'base64') });
  await form.locator('[name="company"]').fill('Próba CMS');
  await form.locator('[name="customerName"]').fill('Administrator testowy');
  await form.locator('[name="email"]').fill(email);
  await form.locator('[name="consent"]').check();
  await form.locator('[name="termsAccepted"]').check();
  await form.locator('#order-review').click();
  await form.locator('#order-confirm .order-preview img').waitFor({ state: 'visible' });
  await form.locator('#order-confirm .button').click();
  await page.locator('#ads-order-dialog').waitFor({ state: 'hidden' });
  await page.locator('#ads-notice').getByText('Bezpłatne ogłoszenie zapisane i zatwierdzone.').waitFor();
  const row = db.prepare("SELECT data FROM ad_orders WHERE json_extract(data,'$.title')=?").get(title);
  assert.ok(row, 'complimentary order persisted');
  const created = JSON.parse(row.data); adId = created.id;
  assert.equal(created.paymentStatus, 'not_required'); assert.equal(created.status, 'approved'); assert.equal(created.totalPrice, 0);
  assert.equal(created.source, 'manual'); assert.equal(created.type, 'PREMIUM'); assert.ok(created.image);
  assert.ok((await (await fetch(`${origin}/api/ads?action=public&language=pl`)).json()).ads.some(ad => ad.id === adId));
  await page.goto(`${origin}/ogloszenia/`);
  await page.locator('[data-ad-list="PREMIUM"] .premium-banner__link:not(.ad-placeholder) img').first().waitFor({ state: 'visible' });
  await page.goto(`${origin}/admin/`);
  await page.locator('[data-view="ads"]').click();
  await page.locator(`#ads-orders [data-ad-shared-edit="${adId}"]`).waitFor({ state: 'visible' });
  for (const [status, visible] of [['paused', false], ['approved', true]]) {
    await page.locator(`#ads-orders [data-ad-shared-edit="${adId}"]`).click();
    form = page.frameLocator('#ads-order-frame');
    await form.locator('[name="adminStatus"]').selectOption(status);
    await form.locator('[name="consent"]').check();
    await form.locator('[name="termsAccepted"]').check();
    await form.locator('#order-review').click();
    await form.locator('#order-confirm .button').click();
    await page.locator('#ads-order-dialog').waitFor({ state: 'hidden' });
    await page.locator(`#ads-orders [data-ad-shared-edit="${adId}"]`).waitFor({ state: 'visible' });
    assert.equal((await (await fetch(`${origin}/api/ads?action=public&language=pl`)).json()).ads.some(ad => ad.id === adId), visible);
  }

  await page.locator(`#ads-orders [data-ad-shared-edit="${adId}"]`).click();
  form = page.frameLocator('#ads-order-frame');
  await form.locator('[data-title="pl"]').waitFor({ state: 'visible' });
  await form.locator('[name="type"][value="TOP"]').check();
  await form.locator(`#order-calendar button[data-date="${today}"]`).click();
  await form.locator(`#order-calendar button[data-date="${nextDay}"]`).click();
  await form.locator('[data-title="pl"]').fill(`${title} – TOP`);
  await form.locator('[name="imageFile"]').setInputFiles({ name: 'top.png', mimeType: 'image/png', buffer: Buffer.from(picture, 'base64') });
  await form.locator('[name="consent"]').check();
  await form.locator('[name="termsAccepted"]').check();
  await form.locator('#order-review').click();
  await form.locator('#order-confirm .button').click();
  await page.locator('#ads-order-dialog').waitFor({ state: 'hidden' });
  await page.locator('#ads-notice').getByText('Zmiany ogłoszenia zapisane.').waitFor();
  const changed = JSON.parse(db.prepare('SELECT data FROM ad_orders WHERE id=?').get(adId).data);
  assert.equal(changed.type, 'TOP'); assert.equal(changed.startDate, nextDay); assert.equal(changed.title, `${title} – TOP`);
  assert.equal(changed.paymentStatus, 'not_required'); assert.equal(changed.totalPrice, 0); assert.notEqual(changed.image, created.image);

  await page.locator(`#ads-orders [data-ad-shared-edit="${adId}"]`).click();
  form = page.frameLocator('#ads-order-frame');
  await form.locator('[name="adminStatus"]').selectOption('paused');
  await form.locator('[name="consent"]').check();
  await form.locator('[name="termsAccepted"]').check();
  await form.locator('#order-review').click();
  await form.locator('#order-confirm .button').click();
  await page.locator('#ads-order-dialog').waitFor({ state: 'hidden' });
  await page.locator('#ads-notice').getByText('Zmiany ogłoszenia zapisane.').waitFor();
  assert.equal(JSON.parse(db.prepare('SELECT data FROM ad_orders WHERE id=?').get(adId).data).status, 'paused');
  await page.locator(`#ads-orders [data-ad-edit="${adId}"]`).click();
  await page.locator('#ads-delete').click();
  await page.locator('#cms-confirm-accept').click();
  await page.locator('#ads-notice').getByText('Ogłoszenie usunięte.').waitFor();
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM ad_orders WHERE id=?').get(adId).n, 0);
  console.log('Admin free ad browser E2E: shared form, PREMIUM banner, zero payment, public display, edit, TOP artwork, pause, delete OK');
} finally {
  await browser?.close();
  if (adId) { db.prepare('DELETE FROM ad_order_history WHERE order_id=?').run(adId); db.prepare('DELETE FROM ad_orders WHERE id=?').run(adId); }
  db.prepare('DELETE FROM cms_sessions WHERE user_id=?').run(adminId);
  db.prepare('DELETE FROM cms_audit WHERE actor_id=?').run(adminId);
  db.prepare('DELETE FROM cms_users WHERE id=?').run(adminId);
  if (originalSettings) db.prepare('UPDATE ads_settings SET data=?,version=? WHERE id=1').run(originalSettings.data, originalSettings.version);
  else db.prepare('DELETE FROM ads_settings WHERE id=1').run();
  db.close();
}
