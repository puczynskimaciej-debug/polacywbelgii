import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { randomBytes, randomUUID } from 'node:crypto';
import { chromium } from 'playwright-core';
import { localD1Path } from '../agent/local-db.mjs';
import { hashPassword } from '../cloudflare/auth.mjs';

const origin = process.env.LOCAL_CMS_ORIGIN || 'http://localhost:8080';
const db = new DatabaseSync(localD1Path());
db.exec('PRAGMA busy_timeout=5000');
const id = randomUUID();
const password = randomBytes(32).toString('base64url');
const email = `browser-${id.slice(0, 12)}@example.invalid`;
const slug = `browser-${id.slice(0, 12)}`;
const aiId = randomBytes(10).toString('hex');
const articlePath = `src/content/articles/${slug}.md`;
let browser;
try {
  db.prepare('INSERT INTO cms_users(id,email,name,password_hash,role,active,must_change_password) VALUES(?,?,?,?,?,1,0)').run(id,email,'Browser E2E',await hashPassword(password),'admin');
  browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH || 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true });
  const context = await browser.newContext();
  const page = await context.newPage();
  await page.goto(`${origin}/admin/`);
  await page.locator('#login-form [name="email"]').fill(email);
  await page.locator('#login-form [name="password"]').fill(password);
  await page.locator('#login-form [type="submit"]').click();
  await page.locator('#app-view').waitFor({ state: 'visible', timeout: 15000 });
  await page.locator('[data-view="articles"]').click();
  await page.locator('[data-action="new-article"]').click();
  await page.locator('#article-form [name="title"]').fill('Przeglądarkowy test D1');
  await page.locator('#article-form [name="description"]').fill('Opis testowy w CMS');
  await page.locator('#article-form [name="body"]').fill('Treść testowa lokalnego szkicu.');
  await page.locator('#article-form [name="slug"]').evaluate((input, value) => { input.value = value; }, slug);
  await page.locator('#article-form [name="status"]').selectOption('draft');
  await page.locator('#article-form [type="submit"]').click();
  await page.waitForFunction(() => !document.querySelector('#article-dialog').open);
  assert.equal(db.prepare('SELECT status FROM cms_content WHERE path=?').get(articlePath)?.status, 'draft');
  await page.locator('.nav-item[data-view="articles"]').click();
  await page.locator(`[data-edit-article="${slug}"]`).click();
  await page.locator('#article-form [name="status"]').selectOption('published');
  await page.locator('#article-form [type="submit"]').click();
  await page.waitForFunction(() => !document.querySelector('#article-dialog').open);
  assert.equal((await fetch(`${origin}/artykuly/${slug}/`)).status, 200);
  await page.locator(`[data-unpublish-article="${slug}"]`).click();
  await page.locator('#cms-confirm-accept').click();
  await page.waitForFunction(path => document.querySelector(`[data-unpublish-article="${path}"]`) === null,slug);
  assert.equal((await fetch(`${origin}/artykuly/${slug}/`)).status, 404);
  assert.equal(db.prepare('SELECT status FROM cms_content WHERE path=?').get(articlePath)?.status,'draft');
  await page.locator('.nav-item[data-view="ai-editor"]').click();
  await page.locator('[data-panel="ai-editor"]').waitFor({ state: 'visible' });
  const at=new Date().toISOString();
  db.prepare('INSERT INTO ai_candidates(id,kind,status,title,description,body,sources_json,verification_json,ai_generated,created_at,updated_at) VALUES(?,?,?,?,?,?,?,?,1,?,?)').run(aiId,'article','pending_review','Artykuł testowy AI','Opis szkicu AI','Treść szkicu AI. '.repeat(15),JSON.stringify([{url:'https://www.gov.pl/web/belgia/praca-i-pobyt'}]),JSON.stringify({status:'needs_review'}),at,at);
  db.prepare("INSERT INTO ai_editorial(candidate_id,status,owner_kind,owner_id,updated_at) VALUES(?,'pending_review','agent','agent',?)").run(aiId,at);
  await page.locator('.nav-item[data-view="articles"]').click();
  await page.locator(`[data-edit-ai="${aiId}"]`).waitFor();
  await page.locator(`[data-edit-ai="${aiId}"]`).click();
  assert.equal(await page.locator('#article-form [data-language-tab="en"]').isVisible(),false);
  await page.locator('#article-form [data-language-tab="nl"]').click();
  await page.locator('#article-form [name="title_nl"]').fill('Nederlandse testtitel');
  await page.locator('#article-form [name="description_nl"]').fill('Nederlandse beschrijving');
  await page.locator('#article-form [name="body_nl"]').fill('Nederlandse tekst van het artikel.');
  await page.locator('#article-form [name="tags"]').fill('test, cms');
  await page.locator('#article-form [type="submit"]').click();
  await page.waitForFunction(() => !document.querySelector('#article-dialog').open);
  const fields=JSON.parse(db.prepare('SELECT article_fields_json FROM ai_candidates WHERE id=?').get(aiId).article_fields_json);
  assert.equal(fields.title_nl,'Nederlandse testtitel');
  assert.equal(fields.tags,'test, cms');
  assert.equal(JSON.parse(db.prepare('SELECT verification_json FROM ai_candidates WHERE id=?').get(aiId).verification_json).status,'needs_review');
  console.log('CMS browser E2E: D1 draft, publish, shared AI editor and locales OK');
} finally {
  await browser?.close();
  db.prepare('DELETE FROM ai_candidate_history WHERE candidate_id=?').run(aiId);
  db.prepare('DELETE FROM ai_editorial WHERE candidate_id=?').run(aiId);
  db.prepare('DELETE FROM ai_candidates WHERE id=?').run(aiId);
  db.prepare('DELETE FROM cms_content WHERE path=?').run(articlePath);
  db.prepare('DELETE FROM cms_content_history WHERE path=?').run(articlePath);
  db.prepare('DELETE FROM cms_sessions WHERE user_id=?').run(id);
  db.prepare('DELETE FROM cms_audit WHERE actor_id=?').run(id);
  db.prepare('DELETE FROM cms_users WHERE id=?').run(id);
  db.close();
}
